// Package tt вшивает номер версии в бинарник.
//
// go:embed не умеет ссылаться на родительский каталог, а файл VERSION лежит в
// корне репозитория — поэтому директива живёт здесь, рядом с ним, а не в
// internal/cli. Тот же приём уже применён к веб-бандлу в web/embed.go.
//
// VERSION — единственное место, где живёт номер версии: его читают и этот
// бинарник, и installer/windows/tt.iss (препроцессором ISPP), и
// installer/macos/build.sh. Вариант с -ldflags дал бы версию только бинарнику,
// а установщикам всё равно понадобился бы отдельный источник — то есть второе
// место, где число правят руками. Именно поэтому установщик всё время
// назывался 1.0.0, хотя поставка менялась несколько раз за день.
package tt

import (
	_ "embed"
	"strings"
)

//go:embed VERSION
var versionRaw string

// Version — номер версии без завершающего перевода строки.
func Version() string {
	return strings.TrimSpace(versionRaw)
}
