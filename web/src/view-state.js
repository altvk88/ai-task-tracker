// Что запоминается между загрузками страницы (TT-059) и что нет.
//
// Запоминаем только выбранные проекты — localStorage, не sessionStorage:
// человек, ведущий один проект, должен получать его же после перезапуска
// сервера и закрытия вкладки, а не только в рамках одной сессии (в отличие
// от токена записи в store.js — тот, наоборот, намеренно не переживает
// закрытие вкладки).
//
// Хранится набор, а не одно значение (TT-062): дропдаун с чекбоксами
// позволяет показывать несколько проектов сразу, и запоминать нужно ровно
// то же самое, иначе после этой задачи память фильтра пришлось бы
// переписывать ещё раз.
//
// Параметр в адресе строки не используется: это дало бы шаринг ссылки на
// отфильтрованную доску, но задача — не потерять фильтр при обычном F5,
// а не сделать ссылку для коллеги. Можно добавить отдельно, если понадобится.
//
// Не запоминаются: поиск (сессионный контекст, который вводящий забудет —
// доска на следующий день покажется пустой без понятной причины), галочка
// «показывать старые закрытые» (по умолчанию безопаснее прятать, чем
// внезапно показать тысячу старых закрытых записей) и вкладка Доска/Пульс
// (открыли по ссылке или после F5 — ожидаемый старт всегда «Доска»).

const KEY = 'tt-projects';

/** Сохранённый набор проектов или [] — включая приватный режим без исключений. */
export function loadStoredProjects() {
  try {
    const raw = JSON.parse(localStorage.getItem(KEY) ?? '[]');
    return Array.isArray(raw) ? raw.filter((p) => typeof p === 'string') : [];
  } catch {
    return [];
  }
}

/** Сохраняет набор; тихо не срабатывает без доступа к хранилищу. */
export function storeProjects(selected) {
  try {
    if (selected.length) localStorage.setItem(KEY, JSON.stringify(selected));
    else localStorage.removeItem(KEY);
  } catch {
    // приватный режим, отключённое хранилище и т.п. — запоминать негде
  }
}

/**
 * Чистая функция: сохранённый набор + список проектов из снимка → что
 * реально показывать. Проекты, которых больше нет (переименовали, удалили,
 * открыли другой vault), тихо выпадают из набора. Пустой результат не ломает
 * доску: по принятому смыслу пустого набора (см. projectMatches) это те же
 * «Все проекты», а не пустой экран без объяснения.
 */
export function resolveSelectedProjects(stored, availableProjects) {
  const available = new Set(availableProjects);
  return stored.filter((p) => available.has(p));
}

/**
 * true, если таска попадает под текущий выбор. Пустой набор трактуется как
 * «Все проекты» — так снявший последнюю галочку получает полную доску, а не
 * пустую: пустой экран без объяснения хуже, чем неотфильтрованный.
 */
export function projectMatches(selected, project) {
  return selected.length === 0 || selected.includes(project);
}

/**
 * Подпись на кнопке дропдауна фильтра: имя набора не влезает в строку, когда
 * проектов много, поэтому одно имя — только при выборе ровно одного проекта,
 * иначе — количество. Выбор всех существующих проектов не отличается от
 * пустого набора («Все проекты»): для человека это один и тот же результат.
 */
export function describeProjectSelection(selected, available) {
  if (selected.length === 0 || selected.length >= available.length) return 'Все проекты';
  if (selected.length === 1) return selected[0];
  return `${selected.length} ${pluralProjects(selected.length)}`;
}

function pluralProjects(n) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return 'проект';
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return 'проекта';
  return 'проектов';
}
