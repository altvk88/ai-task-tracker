package vault

import "testing"

func TestQuote(t *testing.T) {
	cases := []struct{ in, want string }{
		{"ready", "ready"},
		{"", ""},
		{"2026-08-31", "2026-08-31"},
		{"M", "M"},
		{"Обычный заголовок без спецсимволов", "Обычный заголовок без спецсимволов"},
		{"Баг (прод): всё сломалось", `"Баг (прод): всё сломалось"`},
		{"Хвост с двоеточием:", `"Хвост с двоеточием:"`},
		{"`Accept` и `Cancel` в строке", "\"`Accept` и `Cancel` в строке\""},
		{"[не список]", `"[не список]"`},
		{"- не элемент", `"- не элемент"`},
		{"#не комментарий", `"#не комментарий"`},
		{"true", `"true"`},
		{"NO", `"NO"`},
		{"null", `"null"`},
		{" пробел слева", `" пробел слева"`},
		{"пробел справа ", `"пробел справа "`},
		{`кавычка " внутри`, `"кавычка \" внутри"`},
		{`бэкслеш \ внутри`, `"бэкслеш \\ внутри"`},
	}
	for _, c := range cases {
		if got := quote(c.in); got != c.want {
			t.Errorf("quote(%q) = %q, ожидалось %q", c.in, got, c.want)
		}
	}
}
